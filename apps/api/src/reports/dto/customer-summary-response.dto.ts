import { ApiProperty } from '@nestjs/swagger';

export class CustomerSummaryResponseDto {
  @ApiProperty({ description: 'Total registered customers with CUSTOMER role', example: 450 })
  totalCustomers: number;

  @ApiProperty({ description: 'New customer registrations within the period', example: 38 })
  newCustomers: number;

  @ApiProperty({ description: 'Active customers with orders within the period or active status', example: 120 })
  activeCustomers: number;

  @ApiProperty({ description: 'Distinct customers who have placed at least one non-cancelled order', example: 110 })
  purchasingCustomers: number;

  @ApiProperty({ description: 'Repeat customers with 2 or more non-cancelled orders', example: 45 })
  repeatCustomers: number;

  @ApiProperty({ description: 'Repeat customer rate as percentage of purchasing customers', example: 40.91 })
  repeatCustomerRate: number;

  @ApiProperty({ description: 'Total cumulative orders placed by customers in the period', example: 215 })
  totalOrders: number;

  @ApiProperty({ description: 'Total cumulative revenue generated by customers in the period', example: 540000.0 })
  totalRevenue: number;

  @ApiProperty({ description: 'Average customer lifetime value / revenue per purchasing customer', example: 4909.09 })
  averageCustomerValue: number;

  @ApiProperty({ description: 'Average order count per purchasing customer', example: 1.95 })
  averageOrdersPerCustomer: number;

  @ApiProperty({ description: 'Customers who have never placed an order', example: 135 })
  zeroOrderCustomers: number;

  @ApiProperty({ description: 'Customers with deactivated accounts', example: 8 })
  inactiveCustomersCount: number;

  @ApiProperty({ description: 'Store currency code', example: 'BDT' })
  currency: string;

  @ApiProperty({ description: 'Filter start date in ISO format', required: false })
  startDate?: string;

  @ApiProperty({ description: 'Filter end date in ISO format', required: false })
  endDate?: string;
}
